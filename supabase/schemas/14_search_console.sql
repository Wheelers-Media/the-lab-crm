-- Google search performance for the shop's website, copied from Google Search
-- Console by the search_console_sync function: clicks, impressions and average
-- position per day, and per day for each search phrase and page. Source of
-- truth; migration 20261030120000_search_console.sql.
create table public.search_console_daily (
    id bigint generated by default as identity primary key,
    day date not null unique,
    clicks integer not null default 0,
    impressions integer not null default 0,
    -- average position in the results, 1 is the top
    position numeric(6, 2) not null default 0,
    synced_at timestamp with time zone not null default now()
);

create table public.search_console_queries (
    id bigint generated by default as identity primary key,
    day date not null,
    -- what was typed into Google
    query text not null,
    clicks integer not null default 0,
    impressions integer not null default 0,
    position numeric(6, 2) not null default 0,
    synced_at timestamp with time zone not null default now(),
    constraint search_console_queries_key unique (day, query)
);
create index search_console_queries_day_idx on public.search_console_queries (day);

create table public.search_console_pages (
    id bigint generated by default as identity primary key,
    day date not null,
    -- the page Google showed, as a full URL
    page text not null,
    clicks integer not null default 0,
    impressions integer not null default 0,
    position numeric(6, 2) not null default 0,
    synced_at timestamp with time zone not null default now(),
    constraint search_console_pages_key unique (day, page)
);
create index search_console_pages_day_idx on public.search_console_pages (day);

alter table public.search_console_daily enable row level security;
alter table public.search_console_queries enable row level security;
alter table public.search_console_pages enable row level security;
create policy "Enable read access for authenticated users" on public.search_console_daily for select to authenticated using (true);
create policy "Enable read access for authenticated users" on public.search_console_queries for select to authenticated using (true);
create policy "Enable read access for authenticated users" on public.search_console_pages for select to authenticated using (true);
grant select on table public.search_console_daily to authenticated;
grant select on table public.search_console_queries to authenticated;
grant select on table public.search_console_pages to authenticated;
grant all on table public.search_console_daily to service_role;
grant all on table public.search_console_queries to service_role;
grant all on table public.search_console_pages to service_role;
