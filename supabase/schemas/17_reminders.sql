-- Daily reminders on the team's phones (supabase/functions/reminders).
-- Source of truth; migration 20261122120000_daily_reminders.sql.

-- One row per reminder sent, so each goes out once a day. sales_id 0 is a
-- reminder for the whole team (the show check and the end-of-day numbers).
create table public.reminder_log (
    id bigint generated by default as identity primary key,
    kind text not null,
    day date not null,
    sales_id bigint not null default 0,
    sent_at timestamp with time zone not null default now(),
    constraint reminder_log_once_a_day unique (kind, day, sales_id)
);
alter table public.reminder_log enable row level security;
-- Server only: no policies, so the app cannot read or write it
grant all on table public.reminder_log to service_role;

-- The shop's numbers at the end of each weekday, kept to track the shop over time
create table public.shop_day_log (
    day date primary key,
    stats jsonb not null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint shop_day_log_stats_is_object check (jsonb_typeof(stats) = 'object')
);
alter table public.shop_day_log enable row level security;
create policy "Team can read the shop log" on public.shop_day_log for select to authenticated using (true);
grant select on table public.shop_day_log to authenticated;
grant all on table public.shop_day_log to service_role;
