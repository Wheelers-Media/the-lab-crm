-- Online store traffic copied from Shopify's reports (ShopifyQL "sessions") by
-- the traffic_sync function: one row per day, referrer and device. Needs the
-- app's read_reports scope. Mirrors supabase/schemas/13_shop_traffic.sql.
create table if not exists public.shop_traffic_daily (
    id bigint generated by default as identity primary key,
    day date not null,
    referrer_source text not null default '',
    referrer_name text not null default '',
    device_type text not null default '',
    sessions integer not null default 0,
    cart_sessions integer not null default 0,
    checkout_sessions integer not null default 0,
    completed_sessions integer not null default 0,
    synced_at timestamp with time zone not null default now(),
    constraint shop_traffic_daily_key unique (day, referrer_source, referrer_name, device_type)
);
create index if not exists shop_traffic_daily_day_idx on public.shop_traffic_daily (day);

alter table public.shop_traffic_daily enable row level security;
drop policy if exists "Enable read access for authenticated users" on public.shop_traffic_daily;
create policy "Enable read access for authenticated users" on public.shop_traffic_daily for select to authenticated using (true);
grant select on table public.shop_traffic_daily to authenticated;
grant all on table public.shop_traffic_daily to service_role;
