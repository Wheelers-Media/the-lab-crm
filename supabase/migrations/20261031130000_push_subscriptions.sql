-- Phones and computers that have switched on CRM alerts (Web Push). One row per
-- device; the endpoint is the browser's own address for it. The alert senders
-- (lead_intake, calcom_webhook, shopify_webhook) read this with the service role.
-- Mirrors supabase/schemas/15_push_subscriptions.sql.
create table if not exists public.push_subscriptions (
    id bigint generated by default as identity primary key,
    sales_id bigint not null references public.sales(id) on delete cascade,
    endpoint text not null unique,
    p256dh text not null,
    auth text not null,
    prefs jsonb not null default '{}'::jsonb,
    user_agent text,
    created_at timestamp with time zone not null default now(),
    last_sent_at timestamp with time zone,
    constraint push_subscriptions_prefs_is_object check (jsonb_typeof(prefs) = 'object')
);
create index if not exists push_subscriptions_sales_id_idx on public.push_subscriptions (sales_id);

alter table public.push_subscriptions enable row level security;
drop policy if exists "Own devices" on public.push_subscriptions;
create policy "Own devices" on public.push_subscriptions for all to authenticated
    using (sales_id = (select id from public.sales where user_id = auth.uid()))
    with check (sales_id = (select id from public.sales where user_id = auth.uid()));
grant select, insert, update, delete on table public.push_subscriptions to authenticated;
grant all on table public.push_subscriptions to service_role;
