-- The commission roles an order's lines carry, from the products' Shopify tags
-- ("commission:tune" -> tune). Lines name their product id; older lines without
-- one are matched by the product's title.
create or replace function public.referral_order_roles(line_items jsonb)
returns text[]
language sql stable
set search_path = public
as $$
    select coalesce(array_agg(distinct lower(substr(t, 12))), '{}')
    from jsonb_array_elements(coalesce(line_items, '[]'::jsonb)) li
    join public.packages p
      on p.shopify_product_id = li->>'product_id'
      or (li->>'product_id' is null
          and (lower(li->>'name') = lower(p.shopify_title)
               or lower(li->>'name') like lower(p.shopify_title) || ' - %'))
    cross join unnest(p.tags) t
    where t ilike 'commission:_%'
$$;

-- Every commission line: what each credited order earned, and the deduction a
-- refund or cancellation inside the refund window makes the month after.
create or replace view public.referral_lines with (security_invoker = on) as
with credited as (
    select o.id as order_id, o.order_number, o.ordered_at, o.contact_id, o.total,
           o.cancelled_at, o.refunded_at, o.financial_status,
           pr.code as program_code, pr.refund_days,
           case when o.referral_code = pr.code then 'link'
                when c.referral_code = pr.code
                     and o.ordered_at >= c.referred_at
                     and o.ordered_at < c.referred_at + make_interval(days => pr.window_days) then 'customer'
                else 'claim' end as credited_by,
           coalesce(o.referral_keyword, c.referral_keyword) as keyword,
           nullif(trim(concat_ws(' ', c.first_name, c.last_name)), '') as customer,
           public.referral_order_roles(o.line_items) as roles
    from public.orders o
    join public.referral_programs pr on pr.active
    left join public.contacts c on c.id = o.contact_id
    where not o.is_deposit
      -- paid in full: a deposit, a part payment or an unpaid invoice earns nothing yet
      and o.financial_status in ('paid', 'partially_refunded', 'refunded')
      and (o.referral_code = pr.code
           or (c.referral_code = pr.code
               and o.ordered_at >= c.referred_at
               and o.ordered_at < c.referred_at + make_interval(days => pr.window_days))
           or exists (select 1 from public.referral_claims rc
                      where rc.program_code = pr.code and rc.contact_id = o.contact_id
                        and o.ordered_at >= rc.claimed_at - interval '7 days'
                        and o.ordered_at < rc.claimed_at + make_interval(days => pr.window_days)))
),
earned as (
    select cr.*, best.label as rule, best.needs as rule_needs, best.amount
    from credited cr
    join lateral (
        select r.label, r.needs, r.amount from public.referral_rules r
        where r.program_code = cr.program_code and r.needs <@ cr.roles
        order by r.amount desc limit 1
    ) best on true
    where best.amount > 0
)
select concat(program_code, '-', order_id) as id, program_code,
       date_trunc('month', ordered_at at time zone 'America/Dawson_Creek')::date as month,
       'earned' as kind, order_id, order_number, ordered_at, contact_id, customer, keyword,
       credited_by, roles, rule, cardinality(rule_needs) > 1 as full_kit, amount
from earned
union all
-- ponytail: a partial refund leaves the commission alone; only a full refund or a cancellation takes it back
select concat(program_code, '-', order_id, '-refund'), program_code,
       (date_trunc('month', ordered_at at time zone 'America/Dawson_Creek') + interval '1 month')::date,
       'refund', order_id, order_number, ordered_at, contact_id, customer, keyword,
       credited_by, roles, rule, cardinality(rule_needs) > 1, -amount
from earned
where (cancelled_at is not null and cancelled_at < ordered_at + make_interval(days => refund_days))
   or (financial_status = 'refunded' and coalesce(refunded_at, ordered_at) < ordered_at + make_interval(days => refund_days));

-- The monthly scoreboard: leads, quotes, open checkouts, paid kits and what is owed
create or replace view public.referral_months with (security_invoker = on) as
with months as (
    select program_code, month from public.referral_lines
    union
    select d.referral_code, date_trunc('month', d.created_at at time zone 'America/Dawson_Creek')::date
    from public.deals d where d.referral_code is not null
    union
    select s.referral_code, date_trunc('month', s.created_at at time zone 'America/Dawson_Creek')::date
    from public.shopify_checkouts s where s.referral_code is not null
),
lines as (
    select program_code, month,
           count(*) filter (where kind = 'earned' and full_kit) as full_kits,
           count(*) filter (where kind = 'earned' and not full_kit) as half_kits,
           coalesce(sum(amount) filter (where kind = 'earned'), 0) as earned,
           coalesce(sum(amount) filter (where kind = 'refund'), 0) as refunds
    from public.referral_lines group by 1, 2
)
select concat(m.program_code, '-', m.month) as id, m.program_code, m.month,
       (select count(*) from public.deals d
         where d.referral_code = m.program_code
           and date_trunc('month', d.created_at at time zone 'America/Dawson_Creek')::date = m.month) as leads,
       (select count(*) from public.deals d
         where d.referral_code = m.program_code and d.quote is not null
           and date_trunc('month', d.created_at at time zone 'America/Dawson_Creek')::date = m.month) as quotes,
       (select count(*) from public.shopify_checkouts s
         where s.referral_code = m.program_code and s.completed_at is null
           and date_trunc('month', s.created_at at time zone 'America/Dawson_Creek')::date = m.month) as open_checkouts,
       coalesce(l.full_kits, 0) as full_kits,
       coalesce(l.half_kits, 0) as half_kits,
       coalesce(l.earned, 0) as earned,
       p.monthly_cap,
       coalesce(l.refunds, 0) as refunds,
       least(coalesce(l.earned, 0), p.monthly_cap) + coalesce(l.refunds, 0) as owed
from months m
join public.referral_programs p on p.code = m.program_code
left join lines l on l.program_code = m.program_code and l.month = m.month;

-- Everyone signed in reads; the program and rules are edited in the CRM (Eric);
-- a partner adds and removes their own claims; the functions write the tags.
alter table public.referral_programs enable row level security;
alter table public.referral_rules enable row level security;
alter table public.referral_claims enable row level security;
drop policy if exists "Authenticated users manage referral programs" on public.referral_programs;
create policy "Authenticated users manage referral programs" on public.referral_programs for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users manage referral rules" on public.referral_rules;
create policy "Authenticated users manage referral rules" on public.referral_rules for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users read referral claims" on public.referral_claims;
create policy "Authenticated users read referral claims" on public.referral_claims for select to authenticated using (true);
drop policy if exists "Authenticated users add referral claims" on public.referral_claims;
create policy "Authenticated users add referral claims" on public.referral_claims for insert to authenticated with check (claimed_by = auth.uid());
drop policy if exists "Claimers remove their own claims" on public.referral_claims;
create policy "Claimers remove their own claims" on public.referral_claims for delete to authenticated using (claimed_by = auth.uid());

grant select, insert, update, delete on public.referral_programs, public.referral_rules to authenticated;
grant select, insert, delete on public.referral_claims to authenticated;
grant all on public.referral_programs, public.referral_rules, public.referral_claims to service_role;
grant select on public.referral_lines, public.referral_months to authenticated, service_role;
grant execute on function public.referral_order_roles(jsonb) to authenticated, service_role;
