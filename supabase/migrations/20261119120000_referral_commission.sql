-- Referral tracking and commission. A partner link (thelabfsj.ca/...?ref=nw&kw=L5P)
-- tags the visitor; the tag rides on the Shopify order (note_attributes "Ref" /
-- "Ref keyword"), the Cal.com booking (metadata ref / kw) and the website lead.
-- The first tag on a customer sticks, so a sale rung up later at the register or
-- on an invoice is still credited while it falls inside the program's window.
-- Eric controls everything from the CRM: the program (cap, window, refund days),
-- the rules (which product roles earn how much) and, in Shopify, which products
-- count, by tagging them "commission:tune", "commission:exhaust" and so on.
-- Mirrors supabase/schemas/16_referrals.sql.

alter table public.contacts
    add column if not exists referral_code text,
    add column if not exists referral_keyword text,
    add column if not exists referred_at timestamp with time zone;
alter table public.deals
    add column if not exists referral_code text,
    add column if not exists referral_keyword text;
alter table public.orders
    add column if not exists referral_code text,
    add column if not exists referral_keyword text,
    add column if not exists refunded_at timestamp with time zone;
alter table public.appointments
    add column if not exists referral_code text,
    add column if not exists referral_keyword text;
alter table public.shopify_checkouts
    add column if not exists referral_code text,
    add column if not exists referral_keyword text;
create index if not exists contacts_referral_code_idx on public.contacts (referral_code) where referral_code is not null;
create index if not exists orders_referral_code_idx on public.orders (referral_code) where referral_code is not null;

-- One row per partner code
create table if not exists public.referral_programs (
    id bigint generated by default as identity primary key,
    code text not null unique check (code ~ '^[a-z0-9]{1,20}$'),
    name text not null,
    monthly_cap numeric not null default 1500 check (monthly_cap >= 0),
    window_days integer not null default 90 check (window_days > 0),
    refund_days integer not null default 30 check (refund_days >= 0),
    active boolean not null default true,
    updated_at timestamp with time zone not null default now()
);

-- An order earns the largest rule whose roles it holds in full: a tune and an
-- exhaust is the full kit, either alone is a half kit. Accessories have no role.
create table if not exists public.referral_rules (
    id bigint generated by default as identity primary key,
    program_code text not null references public.referral_programs (code) on update cascade on delete cascade,
    label text not null,
    needs text[] not null check (cardinality(needs) > 0),
    amount numeric not null check (amount >= 0)
);

-- A partner claiming a customer they closed (an old quote, an open checkout):
-- that customer's paid orders from a week before the claim to the end of the
-- window are credited. Eric sees who claimed and when.
create table if not exists public.referral_claims (
    id bigint generated by default as identity primary key,
    program_code text not null references public.referral_programs (code) on update cascade on delete cascade,
    contact_id bigint not null references public.contacts (id) on delete cascade,
    deal_id bigint references public.deals (id) on delete set null,
    checkout_token text,
    note text,
    claimed_by uuid default auth.uid(),
    claimed_at timestamp with time zone not null default now()
);
create index if not exists referral_claims_contact_idx on public.referral_claims (contact_id);

