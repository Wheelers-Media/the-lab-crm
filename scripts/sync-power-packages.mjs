// Pulls the website's power package definitions (steps, options, Shopify
// handles) from GitHub `main` so the quote builder offers exactly what
// thelabfsj.ca does. Run it whenever the website's packages change:
//   node scripts/sync-power-packages.mjs
// Needs the GitHub CLI signed in (`gh auth status`).
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const REPO = "Wheelers-Media/THE-LAB";
const DIR = "src/assets/js/diesel-packages";
const OUT = path.resolve("src/components/atomic-crm/packages/powerPackages");

const gh = (endpoint) =>
  execFileSync(
    "gh",
    ["api", endpoint, "-H", "Accept: application/vnd.github.raw"],
    {
      encoding: "utf8",
      maxBuffer: 10 * 1024 * 1024,
    },
  );

const listing = JSON.parse(
  execFileSync("gh", ["api", `repos/${REPO}/contents/${DIR}?ref=main`], {
    encoding: "utf8",
  }),
);
mkdirSync(OUT, { recursive: true });
const ids = [];
for (const file of listing.filter((f) => f.name.endsWith(".json"))) {
  const raw = gh(`repos/${REPO}/contents/${DIR}/${file.name}?ref=main`);
  const pretty = JSON.stringify(JSON.parse(raw), null, 2) + "\n";
  writeFileSync(path.join(OUT, file.name), pretty);
  ids.push(file.name.replace(/\.json$/, ""));
}
const index =
  `// Generated by scripts/sync-power-packages.mjs from ${REPO}@main. Do not edit.\n` +
  ids.map((id, i) => `import p${i} from "./${id}.json";`).join("\n") +
  `\n\nexport const POWER_PACKAGE_FILES = [${ids.map((_, i) => `p${i}`).join(", ")}];\n`;
writeFileSync(path.join(OUT, "index.ts"), index);
process.stdout.write(`Synced ${ids.length} power packages\n`);
